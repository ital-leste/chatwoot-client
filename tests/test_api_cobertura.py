@pytest.mark.parametrize("recurso,nome,args,kwargs,verbo,caminho,tem_corpo", CASOS)
def test_contrato_operacao(recurso,nome,args,kwargs,verbo,caminho,tem_corpo):
    chamadas = []
    def responder(req):
        chamadas.append(req)
        return httpx.Response(200, json=[] if recurso == "canned_responses" and nome == "list" else {"ok": True})
    with CWClient("https://chatwoot.exemplo", "token") as cw:
        headers = dict(cw._http.headers)
        cw._http.close()
        cw._http = httpx.Client(
            base_url="https://chatwoot.exemplo/",
            headers=headers,
            transport=httpx.MockTransport(responder),
        )
        resultado = getattr(getattr(cw,recurso),nome)(*args,**kwargs)
    assert resultado == ([] if recurso == "canned_responses" and nome == "list" else {"ok": True})
    assert len(chamadas) == 1
    req = chamadas[0]
    assert req.method == verbo
    assert req.url.path == caminho
    assert req.headers["authorization"] == "Bearer token"
    if tem_corpo:
        assert req.headers["Content-Type"].startswith("application/json")


